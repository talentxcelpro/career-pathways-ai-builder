function normalizeDbExperienceLevel(exp: string | undefined): string | null {
  if (!exp) return null;
  const lower = exp.toLowerCase();
  if (lower === 'fresher' || lower === 'entry-level' || lower === 'entry') return 'fresher';
  if (lower === 'mid-level' || lower === 'mid' || lower === 'junior') return 'mid-level';
  if (lower === 'senior-level' || lower === 'senior' || lower === 'lead') return 'senior-level';
  if (lower === 'executive' || lower === 'director' || lower === 'vp') return 'executive';
  return null;
}

