/**
 * scripts/generate-city-seed-sql.ts
 * Generates deterministic, idempotent SQL to seed city_registry (Wave 1 + Wave 2)
 * without creating duplicate canonical cities for alternate spellings.
 *
 * Run with: npx tsx scripts/generate-city-seed-sql.ts
 */
import * as fs from 'fs';
import * as path from 'path';
import { CITY_REGISTRY_WAVE1, resolveCity } from '../src/lib/geo/cityRegistry';
import { INDIAN_100_EMPLOYMENT_CENTRES } from '../src/config/jobs/indianLocationsTaxonomy';

function esc(str: string): string {
  return str.replace(/'/g, "''");
}

function sqlArray(arr: readonly string[]): string {
  if (!arr || arr.length === 0) return "'{}'::text[]";
  return `ARRAY[${arr.map((s) => `'${esc(s)}'`).join(', ')}]::text[]`;
}

function normalizeRegion(r: string): string {
  const map: Record<string, string> = {
    North: 'NORTH',
    South: 'SOUTH',
    East: 'EAST',
    West: 'WEST',
    Central: 'CENTRAL',
    'North-East': 'NORTH_EAST',
    'Pan-India': 'PAN_INDIA',
  };
  return map[r] || r.toUpperCase().replace('-', '_');
}

const lines: string[] = [
  '-- Auto-generated by scripts/generate-city-seed-sql.ts',
  '-- Seeds Wave 1 (GSC-evidenced cities) and Wave 2 (non-duplicate Indian employment centres)',
  '-- Idempotent: ON CONFLICT (slug) DO UPDATE',
  '',
];

const seenSlugs = new Set<string>();

// ── 1. Wave 1 from CITY_REGISTRY_WAVE1 ────────────────────────────────────────
for (const c of CITY_REGISTRY_WAVE1) {
  if (seenSlugs.has(c.slug)) continue;
  seenSlugs.add(c.slug);

  lines.push(
    `INSERT INTO public.city_registry (` +
      `slug, canonical_name, state_name, country_code, region, tier, hub_type, expansion_wave, ` +
      `aliases, latitude, longitude, industries, gsc_impressions, gsc_clicks, gsc_avg_position, gsc_query_count, gsc_snapshot_date, active` +
      `) VALUES (` +
      `'${esc(c.slug)}', '${esc(c.canonicalName)}', '${esc(c.stateName)}', '${c.countryCode}', '${esc(c.region)}', ${c.tier}, '${esc(c.hubType)}', ${c.wave}, ` +
      `${sqlArray(c.aliases)}, ${c.latitude}, ${c.longitude}, ${sqlArray(c.industries)}, ` +
      `${c.gsc.impressions}, ${c.gsc.clicks}, ${c.gsc.avgPosition}, ${c.gsc.queryCount}, '${c.gsc.lastSnapshot}', ${c.active}` +
      `) ON CONFLICT (slug) DO UPDATE SET ` +
      `canonical_name = EXCLUDED.canonical_name, state_name = EXCLUDED.state_name, region = EXCLUDED.region, ` +
      `tier = EXCLUDED.tier, hub_type = EXCLUDED.hub_type, aliases = EXCLUDED.aliases, ` +
      `latitude = EXCLUDED.latitude, longitude = EXCLUDED.longitude, industries = EXCLUDED.industries, ` +
      `gsc_impressions = EXCLUDED.gsc_impressions, gsc_clicks = EXCLUDED.gsc_clicks, ` +
      `gsc_avg_position = EXCLUDED.gsc_avg_position, gsc_query_count = EXCLUDED.gsc_query_count, ` +
      `gsc_snapshot_date = EXCLUDED.gsc_snapshot_date, active = EXCLUDED.active;`
  );
}

// ── 2. Wave 2 from INDIAN_100_EMPLOYMENT_CENTRES (deduplicated) ───────────────
let wave2Count = 0;
for (const c of INDIAN_100_EMPLOYMENT_CENTRES) {
  // Skip if slug or name resolves to an existing Wave-1 canonical city (e.g. bengaluru -> bangalore)
  if (seenSlugs.has(c.slug) || resolveCity(c.slug) || resolveCity(c.name)) {
    continue;
  }
  // Skip non-city remote placeholder if not in registry
  if (c.slug === 'remote' || c.slug === 'pan-india') continue;
  if (typeof c.latitude !== 'number' || typeof c.longitude !== 'number') continue;

  seenSlugs.add(c.slug);
  wave2Count++;

  lines.push(
    `INSERT INTO public.city_registry (` +
      `slug, canonical_name, state_name, country_code, region, tier, hub_type, expansion_wave, ` +
      `aliases, latitude, longitude, industries, gsc_impressions, gsc_clicks, gsc_avg_position, gsc_query_count, active` +
      `) VALUES (` +
      `'${esc(c.slug)}', '${esc(c.name)}', '${esc(c.state)}', 'IN', '${normalizeRegion(c.region)}', ${c.tier}, '${esc(c.hubType)}', 2, ` +
      `${sqlArray(c.aliases)}, ${c.latitude}, ${c.longitude}, '{}'::text[], 0, 0, 0, 0, true` +
      `) ON CONFLICT (slug) DO NOTHING;`
  );
}

lines.push('');
lines.push('-- Evaluate index readiness for all Wave 1 cities against live jobs table');
lines.push('DO $$');
lines.push('DECLARE');
lines.push('  v_slug TEXT;');
lines.push('BEGIN');
lines.push('  FOR v_slug IN SELECT slug FROM public.city_registry WHERE expansion_wave = 1 AND active = true LOOP');
lines.push('    PERFORM public.evaluate_city_index_readiness(v_slug);');
lines.push('  END LOOP;');
lines.push('END $$;');

const outPath = path.resolve(process.cwd(), 'scratch/seed_city_registry.sql');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join('\n'), 'utf8');

console.log(`Generated ${outPath}: Wave 1 = ${CITY_REGISTRY_WAVE1.length}, Wave 2 = ${wave2Count}, Total = ${seenSlugs.size}`);
