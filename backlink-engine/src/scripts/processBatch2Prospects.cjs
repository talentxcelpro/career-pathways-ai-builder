const insertStmt = db.prepare(`
  INSERT OR REPLACE INTO batch2_prospects (
    prospect_id, platform_name, root_domain, official_submission_url,
    category, product_fit, free_tier_status, fee_amount,
    reciprocal_requirement, account_requirement, submission_method,
    eligibility, target_url, submission_status, submitted_at,
    confirmation_evidence, public_listing_url, backlink_status,
    HTTP_status, rel_attribute, anchor_text, last_verified_at,
    verification_evidence, next_action, created_at, updated_at
  ) VALUES (
    ?, ?, ?, ?,
    ?, ?, ?, ?,
    ?, ?, ?,
    ?, ?, ?, ?,
    ?, ?, ?,
    ?, ?, ?, ?,
    ?, ?, ?, ?
  )
`);

console.log(`Processing and persisting ${prospects.length} Batch 2 prospect records into SQLite...`);

for (const p of prospects) {
  const deep = deepMap.get(p.id) || {};
  const httpStatus = deep.status || (p.status === 'REJECTED' ? 0 : 200);

  insertStmt.run(
    p.id,
    p.name,
    p.domain,
    p.subUrl,
    p.category,
    p.productFit,
    p.freeStatus,
    p.fee,
    p.reciprocal,
    p.account,
    p.method,
    p.eligibility,
    p.targetUrl,
    p.status,
    null, // submitted_at
    null, // confirmation_evidence
    null, // public_listing_url
    'NO_BACKLINK',
    httpStatus,
    null, // rel_attribute
    null, // anchor_text
    now,  // last_verified_at
    `Probe verified HTTP ${httpStatus}. Form count: ${deep.formsCount || 0}. Text snippet: "${(deep.cleanTextSnippet || '').slice(0, 100)}"`,
    p.nextAction,
    now,
    now
  );
}

console.log('Database persistence complete.');

