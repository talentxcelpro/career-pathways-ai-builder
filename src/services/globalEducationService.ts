function resolveGoalKey(goal: string): string {
  const g = goal.toLowerCase().trim();
  for (const key of Object.keys(GOAL_SKILL_MAP)) {
    if (g.includes(key) || key.includes(g)) return key;
  }
  if (g.includes('code') || g.includes('program') || g.includes('develop') || g.includes('software')) return 'software engineer';
  if (g.includes('data') || g.includes('analyt')) return 'data scientist';
  if (g.includes('machine') || g.includes('ai') || g.includes('deep') || g.includes('artificial')) return 'ai researcher';
  if (g.includes('cyber') || g.includes('security') || g.includes('hack')) return 'cybersecurity specialist';
  if (g.includes('finance') || g.includes('invest') || g.includes('banking')) return 'financial analyst';
  if (g.includes('market') || g.includes('seo') || g.includes('brand')) return 'digital marketing manager';
  if (g.includes('hr') || g.includes('people') || g.includes('talent')) return 'hr analytics specialist';
  if (g.includes('supply') || g.includes('logistics') || g.includes('chain')) return 'supply chain manager';
  if (g.includes('design') || g.includes('ux') || g.includes('ui')) return 'ui/ux designer';
  return 'software engineer';
}

function matchPrograms(goalKey: string, budget: string, currentLevel?: string): GlobalProgram[] {
  const allPrograms = SEED_PROGRAMS as GlobalProgram[];
  
  return allPrograms
    .filter(p => {
      // Budget filtering
      if (budget === 'ZERO') return p.potential_zero_cost || p.tuition_cost_usd === 0;
      if (budget === 'UNDER_50K') return p.tuition_cost_usd < 700 || p.potential_zero_cost;
      if (budget === 'UNDER_2L') return p.tuition_cost_usd < 2500 || p.potential_zero_cost;
      return true;
    })
    .filter(p => {
      // Level matching
      if (currentLevel === '10th' || currentLevel === '12th') {
        return p.level === 'bachelor';
      }
      if (currentLevel === 'master') {
        return p.level === 'phd' || p.level === 'master';
      }
      return true;
    })
    .filter(p => {
      const gWord = goalKey.split(' ')[0];
      return p.career_relevance?.some(r => r.toLowerCase().includes(gWord)) ||
             p.field.toLowerCase().includes(gWord) ||
             p.program_title.toLowerCase().includes(gWord);
    })
    .slice(0, 6);
}

function matchScholarships(budget: string): GlobalScholarship[] {
  const all = SEED_SCHOLARSHIPS as GlobalScholarship[];
  if (budget === 'ZERO') return all.filter(s => s.can_make_tuition_zero).slice(0, 4);
  return all.slice(0, 4);
}

