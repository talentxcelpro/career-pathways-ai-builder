export const globalEducationService = {
  getPrograms: async (filters?: GlobalProgramFilters): Promise<GlobalProgram[]> => {
    try {
      let query = supabase.from('education_programs').select('*');
      if (filters?.search) {
        query = query.or(`program_title.ilike.%${filters.search}%,institution_name.ilike.%${filters.search}%,field.ilike.%${filters.search}%`);
      }
      if (filters?.country) query = query.eq('institution_country', filters.country);
      if (filters?.level) query = query.eq('level', filters.level);
      if (filters?.access_type) query = query.eq('access_type', filters.access_type);

      const { data, error } = await query;
      if (error || !data || data.length === 0) {
        return filterLocalPrograms(SEED_PROGRAMS as GlobalProgram[], filters);
      }
      return data;
    } catch {
      return filterLocalPrograms(SEED_PROGRAMS as GlobalProgram[], filters);
    }
  },

  getScholarships: async (filters?: ScholarshipFilters): Promise<GlobalScholarship[]> => {
    try {
      let query = supabase.from('education_scholarships').select('*');
      if (filters?.search) {
        query = query.or(`title.ilike.%${filters.search}%,provider.ilike.%${filters.search}%`);
      }
      if (filters?.provider_country) query = query.eq('provider_country', filters.provider_country);

      const { data, error } = await query;
      if (error || !data || data.length === 0) {
        return filterLocalScholarships(SEED_SCHOLARSHIPS as GlobalScholarship[], filters);
      }
      return data;
    } catch {
      return filterLocalScholarships(SEED_SCHOLARSHIPS as GlobalScholarship[], filters);
    }
  },

  generatePathway
};

function filterLocalPrograms(list: GlobalProgram[], filters?: GlobalProgramFilters): GlobalProgram[] {
  let res = [...list];
  if (!filters) return res;
  if (filters.search) {
    const s = filters.search.toLowerCase();
    res = res.filter(p => p.program_title.toLowerCase().includes(s) || p.institution_name.toLowerCase().includes(s) || p.field.toLowerCase().includes(s));
  }
  if (filters.country) res = res.filter(p => p.institution_country === filters.country);
  if (filters.level) res = res.filter(p => p.level === filters.level);
  if (filters.access_type) res = res.filter(p => p.access_type === filters.access_type);
  if (filters.potential_zero_cost) res = res.filter(p => p.potential_zero_cost || p.tuition_cost_usd === 0);
  return res;
}

function filterLocalScholarships(list: GlobalScholarship[], filters?: ScholarshipFilters): GlobalScholarship[] {
  let res = [...list];
  if (!filters) return res;
  if (filters.search) {
    const s = filters.search.toLowerCase();
    res = res.filter(p => p.title.toLowerCase().includes(s) || p.provider.toLowerCase().includes(s));
  }
  if (filters.provider_country) res = res.filter(p => p.provider_country === filters.provider_country);
  if (filters.can_make_tuition_zero) res = res.filter(p => p.can_make_tuition_zero);
  return res;
}
